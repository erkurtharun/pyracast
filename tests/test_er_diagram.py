_DIAGRAM_LINE = re.compile(
    r"erDiagram"
    r"|    \w+"
    r"|    \w+ \{"
    r"|        [A-Za-z_]\w* [A-Za-z_]\w*(?: [PFU]K(?:, [PFU]K)*)?(?: \"[^\"]*\")?"
    r"|    }"
    r"|    \w+ (?:\|\||\|o)--(?:o\{|o\|) \w+ : \"\w+\""
)


def diagram_lines(document: str) -> list[str]:
    blocks = re.findall(r"```mermaid\n(.*?)```", document, flags=re.DOTALL)
    return [line for block in blocks for line in block.splitlines()]


def test_generation_is_deterministic_and_mermaid_safe() -> None:
    document = generate_er_diagram.generate()
    assert document == generate_er_diagram.generate()
    assert "\r" not in document
    assert document.endswith("\n")
    assert not document.endswith("\n\n")
    lines = diagram_lines(document)
    assert lines
    assert [line for line in lines if not _DIAGRAM_LINE.fullmatch(line)] == []


